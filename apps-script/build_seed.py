"""Generate apps-script/src/Seed.gs from the same seed files the Django app uses,
so both versions always carry identical templates, corrections and decisions."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SEED = ROOT / "pjo" / "seed"
ORDER = ["GA", "GA_Inspection", "BS", "PS", "LOG", "PT_Sub_Line_Engine", "PT_Battery"]


def dump(v):
    return json.dumps(v, ensure_ascii=False, separators=(",", ":"))


templates = {c: json.loads((SEED / "templates" / f"{c}.json").read_text(encoding="utf8")) for c in ORDER}
out = ["// GENERATED by apps-script/build_seed.py from pjo/seed – do not edit by hand.",
       "// Templates are extracted from the CATH-CPS009-B02 Excel forms (Changan Rayong standard).", ""]
out.append("var SEED_TEMPLATES = {")
for c in ORDER:
    out.append(f"  {dump(c)}: {dump(templates[c])},")
out.append("};")
out.append("var SEED_CORRECTIONS = " + dump(json.loads((SEED / "corrections.json").read_text(encoding="utf8"))) + ";")
out.append("var SEED_PENDING = " + dump(json.loads((SEED / "pending_items.json").read_text(encoding="utf8"))) + ";")
out.append("var SEED_SETTINGS = " + dump(json.loads((SEED / "settings.json").read_text(encoding="utf8"))) + ";")
(ROOT / "apps-script" / "src" / "Seed.gs").write_text("\n".join(out) + "\n", encoding="utf8")
print("Seed.gs", (ROOT / "apps-script/src/Seed.gs").stat().st_size, "bytes")
